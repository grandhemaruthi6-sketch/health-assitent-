/**
 * Strict AI Output Validator for Clinical Safety
 * 
 * Rules:
 * 1. Banned words: 'normal', 'healthy', 'good', 'bad', 'disease', 'deficiency', 'anemia' (as diagnostic conclusions)
 * 2. Grounding check: Every number and clinical unit in the output MUST exist in the input findings
 * 3. Never hallucinate causes, medications, or treatment recommendations
 * 4. On validation failure, immediately discard AI text and fall back to template text.
 */

export const BANNED_WORDS = [
  'normal',
  'healthy',
  'good',
  'bad',
  'disease',
  'deficiency',
  'anemia'
];

/**
 * Validates text generated by AI against clinical safety constraints
 * @param {string} generatedText - Text to validate
 * @param {Object} inputContext - Structured input data (values, names, ranges, counts)
 * @returns {{ isValid: boolean, reason: string | null }}
 */
export function validateAiSummaryOutput(generatedText, inputContext = {}) {
  if (!generatedText || typeof generatedText !== 'string') {
    return { isValid: false, reason: 'Empty or non-string AI output' };
  }

  const lowerText = generatedText.toLowerCase();

  // 1. Check for banned diagnostic / qualitative judgment words
  for (const word of BANNED_WORDS) {
    // Word boundary match
    const regex = new RegExp(`\\b${word}\\b`, 'i');
    if (regex.test(lowerText)) {
      return {
        isValid: false,
        reason: `Banned word detected: '${word}'. AI output must not make qualitative health conclusions.`
      };
    }
  }

  // 2. Extract all numbers from generated text
  const outputNumbers = generatedText.match(/\b\d+(?:\.\d+)?\b/g) || [];

  // Extract all valid numbers from inputContext
  const allowedNumbers = new Set();

  if (inputContext.totalFindings != null) allowedNumbers.add(String(inputContext.totalFindings));
  if (inputContext.outsideCount != null) allowedNumbers.add(String(inputContext.outsideCount));
  if (inputContext.withinCount != null) allowedNumbers.add(String(inputContext.withinCount));
  if (inputContext.uncertainCount != null) allowedNumbers.add(String(inputContext.uncertainCount));
  
  // Date parts if present (e.g. 2026, 10, 15)
  if (inputContext.reportDate) {
    const dateNums = inputContext.reportDate.match(/\b\d+\b/g) || [];
    dateNums.forEach(n => allowedNumbers.add(n));
  }

  // Numbers from all findings (values, range boundaries)
  if (Array.isArray(inputContext.findings)) {
    inputContext.findings.forEach(f => {
      const valStr = String(f.value || '');
      const valNums = valStr.match(/\b\d+(?:\.\d+)?\b/g) || [];
      valNums.forEach(n => allowedNumbers.add(n));

      const rangeStr = String(f.referenceRange || '');
      const rangeNums = rangeStr.match(/\b\d+(?:\.\d+)?\b/g) || [];
      rangeNums.forEach(n => allowedNumbers.add(n));
    });
  }

  // Also allow standard grammatical single-digit numbers 1-9 if used in counts
  for (let i = 1; i <= 9; i++) {
    allowedNumbers.add(String(i));
  }

  // Verify that numbers in output exist in allowed input numbers
  for (const num of outputNumbers) {
    // If output number is not in input context
    if (!allowedNumbers.has(num)) {
      return {
        isValid: false,
        reason: `Ungrounded number '${num}' detected in AI output that does not exist in input data.`
      };
    }
  }

  return { isValid: true, reason: null };
}
